class StarPattern2{
	public static void main(String ar[]){
		int n=5;
		for(int l=1;l<=n;l++){
			for(int k=1;k<=n;k++){
				for(int i=1;i<=n;i++){
					for(int j=1;j<=n;j++){
							
						if(l%2==1){
							if(i%2==0)
								System.out.print(" ");
							else
								System.out.print("*");
							
						}
						else{
							if(i%2==1)
								System.out.print(" ");
							else
								System.out.print("*");
						}
						
					}
					
				}
				System.out.println( );

				
			}
			
		}
	}

}
