class StarPattern1{
	public static void main(String ar[]){
		int n=5;
		for(int l=1;l<=n;l++){
			for(int k=1;k<=n;k++){
				for(int i=1;i<=n;i++){
					for(int j=1;j<=n;j++){
						System.out.print("*");
					}
					System.out.print("\t");
				}
				System.out.println( );

				
			}System.out.println( );
			
		}
	}

}
