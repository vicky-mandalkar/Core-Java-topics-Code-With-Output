class DouTri6{
	public static void  main(String ar[]){
		int n=5;

		for(int i=5;i>=1;i--){
			for(int j=i;j<=5;j++){
				System.out.print(j);			
			}
			System.out.println();
		}

		for(int i=2;i<=5;i++){
			for(int j=i;j<=n;j++){
				System.out.print(j);			
			}
			System.out.println();


		}
	}
			
}


