class DouTri9{
	public static void  main(String ar[]){
		int n=5;

		for(int i=5;i>=1;i--){
			for(int j=1;j<=i;j++){
				System.out.print(j);			
			}
			System.out.println();
		}

		for(int i=2;i<=n;i++){
			for(int j=1;j<=i;j++){
				System.out.print(j);			
			}
			System.out.println();
		}

	}
			
}


